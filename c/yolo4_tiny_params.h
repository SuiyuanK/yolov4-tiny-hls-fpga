#define HEADP5_B1_ADDR ALIGN_16(HEADP5_W1_ADDR + 1179648U*2U)
#define HEADP5_W2_ADDR ALIGN_16(HEADP5_B1_ADDR + 512U*2U)
#define HEADP5_B2_ADDR ALIGN_16(HEADP5_W2_ADDR + (OUT_CH*512U)*2U)



/* 计算总使用量和范围检查 */
#define PARAMS_END_ADDR ALIGN_16(HEADP5_B2_ADDR + OUT_CH*2U)
#define PARAMS_TOTAL_SIZE (PARAMS_END_ADDR - PARAMS_BASE_ADDR)

/* --- 动态缓冲区 (Working Buffers) --- */
/* 每个缓冲区大小: 1,500,000 * sizeof(int16_t) = 3,000,000 字节 (约2.86MB) */
#define WORKING_BUF_SIZE 1500000U

/* route 缓冲区起始地址 (紧跟在参数区之后) */
#define ROUTE_BUF_ADDR   ALIGN_16(PARAMS_END_ADDR)

/* conv3_out 缓冲区起始地址 */
#define CONV3_OUT_BUF_ADDR ALIGN_16(ROUTE_BUF_ADDR + (WORKING_BUF_SIZE * 2U))

/* 最终总内存占用检查 */
#define TOTAL_MEM_USAGE_END ALIGN_16(CONV3_OUT_BUF_ADDR + (WORKING_BUF_SIZE * 2U))

#if TOTAL_MEM_USAGE_END > 0x48000000U
#error "Total Memory (Params + Working Buffers) exceeds 32MB range!"
#endif

