/* 固定内存区域：0x46000000 - 0x47FFFFFF (32MB) */
#define PARAMS_BASE_ADDR 0x46000000U

/* 16字节对齐宏 */
#define ALIGN_16(x) (((x) + 15U) & ~15U)

/* BasicConv1: w=32*3*3*3=864, b=32 */
#define BC1_W_ADDR (PARAMS_BASE_ADDR)
#define BC1_B_ADDR ALIGN_16(BC1_W_ADDR + 864U*2U)

/* BasicConv2: w=64*32*3*3=18432, b=64 */
#define BC2_W_ADDR ALIGN_16(BC1_B_ADDR + 32U*2U)
#define BC2_B_ADDR ALIGN_16(BC2_W_ADDR + 18432U*2U)

/* BasicConv3: w=512*512*3*3=2359296, b=512 */
#define BC3_W_ADDR ALIGN_16(BC2_B_ADDR + 64U*2U)
#define BC3_B_ADDR ALIGN_16(BC3_W_ADDR + 2359296U*2U)

/* conv_forP5: w=256*512*1*1=131072, b=256 */
#define CONV_P5_W_ADDR ALIGN_16(BC3_B_ADDR + 512U*2U)
